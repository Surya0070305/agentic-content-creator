post_instructions = """
You are a LinkedIn content writer for a professional audience. Your job is to
turn a blog article into one LinkedIn post that earns attention and invites
discussion.

INPUT
You will receive a blog article and a desired tone: {tone}.

GROUNDING RULES
- Use only facts, numbers, names, and claims that appear in the blog article.
- Do not invent statistics, quotes, or examples.
- If the article is thin or unclear, write a shorter post instead of padding.

STRUCTURE
1. Hook: a first line of under 15 words that makes a reader stop scrolling.
   Use a surprising fact, a sharp question, or a bold but supported claim.
   Do not open with "I'm excited to share" or similar filler.
2. Body: 3 to 5 short paragraphs of 1 to 2 sentences each, with a blank line
   between them. Cover the single most valuable idea in the article, not a
   summary of everything.
3. Takeaway: one clear lesson or insight the reader can apply.
4. Closing question: end with one specific question that invites comments.
5. Hashtags: 3 to 5 relevant hashtags on the last line.

STYLE
- Write in the requested tone and in first person where it sounds natural.
- Plain language, active voice, no jargon unless the audience expects it.
- Use at most 2 emojis, or none if the tone is formal.
- No bullet-heavy formatting, no markdown headings, no bold syntax.
- Length: 120 to 220 words, never more than 250.

OUTPUT
Return only the final post text, ready to paste into LinkedIn.
Do not add explanations, labels like "Hook:", or notes before or after it.
"""

content_agent=create_agent(
    model=llm,
    tools=[gather_info],
    system_prompt=post_instructions

)


mcp = MCPServer("linkedin-agent")
@mcp.tool()
@observe(name='Post Generation')
def Post_Generation(topic, previous_draft='', feedback=''):
    counter=0
    if previous_draft and feedback:
        question = (
            "Revise the previous draft to address the feedback,"
            f"Topic: {topic}\n\n"
            f"Previous draft:\n{previous_draft}\n\n"
            f"Reviewer feedback:\n{feedback}\n\n"
            "Keep what already works and strictly stick to the feedback regarding the lenght and quality"
            "Follow the feedback, but use only facts from the articles. If the articles don't support something, leave it out rather than invent it."

        )
    else:
        question = f'generate a linkedin post for the respective topic--> {topic}'

    print(f'{question}--->Counter {counter}')
    counter+=1
    run_id=str(uuid.uuid4())
    with propagate_attributes(
        session_id=run_id,
        tags=['Linked Agent'],
        metadata={'topic': topic}
    ):
        handler=CallbackHandler()
        linkedin_agent_response=content_agent.invoke(
            {"messages": [("user", question)]},
            config={"callbacks": [handler]},
        )

        messages = linkedin_agent_response["messages"]

        draft = messages[-1].content

        sources = [m.content for m in messages if isinstance(m, ToolMessage)]

        print('Sources Found:', len(sources))

        if sources:
            print("first source:", sources[0][:300])
        else:
            print("no sources found")
        #
        # return blog_agent_response["messages"][-1].content

        return json.dumps({
            'draft': draft,
            'sources': sources,
        })





