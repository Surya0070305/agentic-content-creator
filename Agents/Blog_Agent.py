@observe()
def read_page(link):
    downloaded_info = trafilatura.fetch_url(link)

    text = None
    meta_info = None
    decoded_text_with_capping = None  # added: otherwise a failed download raises an error

    if downloaded_info:
        text = trafilatura.extract(downloaded_info, include_comments=False, include_tables=False)
        if text:
            token = enc.encode(text)
            decoded_text_with_capping = enc.decode(token[:MAX_TOKENS])
            meta_info = trafilatura.extract_metadata(downloaded_info)
        else:
            print("No text extracted from URL")
    else:
        print("No results")

    title = meta_info.title if meta_info else None
    return {
        'title': title,
        'link': link,
        'text': decoded_text_with_capping,
    }

@tool
@observe()
def gather_info(query):
    """Search the web for a topic and return text from the top articles,
        with source URLs. Use a specific query. Call again with a
        different query to cover other angles."""
    final_info = []
    results = web_search(query)
    if not results:
        print("No results found from the web search")
        return final_info
    top_results = results.get('news_results',[])[:3]
    if not top_results:
        print('No results Generated by the search')
        return final_info
    for item in top_results:
        link = item.get('link')
        if not link:
            print('No Link')
            continue
        final_info.append(read_page(link))


    return final_info


